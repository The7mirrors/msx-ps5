#!/usr/bin/env python3
# MSX PS5 (2026-10-10, AI-assisted): the list of libretro-thumbnails' MSX and MSX2 images, built into the app
# (frontend/msx_thumbs.inc), so a game's cover is found by its title even when the collection names it differently
# ("Pay Load (Japan) (Alt 1)" -> "Pay Load (Japan)", "(Japan, Europe)" vs "(Europe)", a title screen when there is
# no box art). Run again to refresh: python3 tools/make_thumbs_index.py
import json, os, re, urllib.request

REPOS = [("Microsoft_-_MSX", "1"), ("Microsoft_-_MSX2", "2")]
FOLDERS = {"Named_Boxarts": "B", "Named_Titles": "T", "Named_Snaps": "S"}
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "frontend", "msx_thumbs.inc")

lines = []
for repo, code in REPOS:
    url = f"https://api.github.com/repos/libretro-thumbnails/{repo}/git/trees/master?recursive=1"
    req = urllib.request.Request(url, headers={"User-Agent": "msx-ps5-thumbs", "Accept": "application/vnd.github+json"})
    tree = json.load(urllib.request.urlopen(req, timeout=60))
    if tree.get("truncated"):
        raise SystemExit(f"{repo}: the tree listing was truncated")
    for e in tree["tree"]:
        m = re.match(r"^(Named_Boxarts|Named_Titles|Named_Snaps)/([^/]+)\.png$", e["path"])
        if m and e["type"] in ("blob", "commit") or (m and e.get("mode") == "120000"):
            lines.append(code + FOLDERS[m.group(1)] + m.group(2))
lines = sorted(set(lines))

def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/make_thumbs_index.py from libretro-thumbnails (Microsoft_-_MSX, Microsoft_-_MSX2).\n")
    f.write("// Each entry: repository (1 = MSX, 2 = MSX2), folder (B = Named_Boxarts, T = Named_Titles, S = Named_Snaps),\n")
    f.write("// then the image's name without .png.\n")
    f.write("static const char* const kMsxThumbs[] = {\n")
    for l in lines:
        f.write("\t" + c_string(l) + ",\n")
    f.write("};\n")
print(f"{len(lines)} images -> {out}")
